"""End-to-end AI card check (spec 7f).

Generate N cards from ONE real source, run every draft through the card checker
against the 50-item gold set with a **pre-set cutoff**, and block the cards that
fail. Reports the three required counts:

  1. correct & useful      (``correct_useful``)
  2. wrong                  (``wrong``) — a wrong fact is worse than no card
  3. correct-but-bad-teaching (``correct_bad_teaching``) — vague/trivial/dup

plus how many were BLOCKED (kept below cutoff or vetoed by the LLM correctness
check). The cutoff is stated before results are seen
(:data:`speedrun.ai.card_checker.PASSING_CUTOFF`) and is applied by
:func:`speedrun.ai.card_checker.block_failing`.

Live vs offline: with AI enabled + a key, cards are generated by the model and
each item's marked answer is verified by the model. With AI off / no key,
generation returns nothing; pass ``items`` explicitly (or use the offline
deterministic checker path) — this module never fabricates generated cards.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

from speedrun.ai.card_checker import DEFAULT_GOLD, PASSING_CUTOFF, block_failing
from speedrun.ai.card_generator import DEFAULT_SOURCE, generate_items
from speedrun.ai.client import LLMClient, default_client
from speedrun.ai.config import ai_enabled


@dataclass
class CardCheckRun:
    source: str
    gold_size: int
    cutoff: float
    n_requested: int
    n_generated: int
    n_passed: int
    n_blocked: int
    correct_useful: int
    wrong: int
    correct_bad_teaching: int
    ai_source: str
    llm_verified: bool
    report: Any = None

    def to_dict(self) -> dict[str, Any]:
        d = {k: v for k, v in self.__dict__.items() if k != "report"}
        return d


def _gold_size(gold_path: Path) -> int:
    import json

    return len(json.loads(Path(gold_path).read_text(encoding="utf-8"))["items"])


def generate_n(
    n: int,
    *,
    source_path: Path = DEFAULT_SOURCE,
    client: LLMClient | None = None,
    batch_size: int = 5,
    max_batches: int = 20,
) -> list[dict]:
    """Generate up to ``n`` items from one source, looping the model until we have
    ``n``, then re-id gen-0001..N.

    Requests come in small ``batch_size`` chunks: a large single request takes
    longer than the client's request timeout (and would also overflow the
    completion token budget), so it returns nothing. Small batches finish well
    inside the timeout. Empty batches are tolerated (transient) up to
    ``max_batches``.
    """
    client = client or default_client()
    items: list[dict] = []
    empty_streak = 0
    for b in range(max_batches):
        if len(items) >= n:
            break
        want = min(batch_size, n - len(items))
        batch = generate_items(
            source_path=source_path,
            n=want,
            client=client,
            id_prefix=f"gen{b}",
        )
        if not batch:
            empty_streak += 1
            if empty_streak >= 3:
                break
            continue
        empty_streak = 0
        items.extend(batch)
    items = items[:n]
    for i, it in enumerate(items, start=1):
        it["id"] = f"gen-{i:04d}"
    return items


def run_card_check(
    *,
    n: int = 50,
    source_path: Path = DEFAULT_SOURCE,
    gold_path: Path = DEFAULT_GOLD,
    cutoff: float = PASSING_CUTOFF,
    client: LLMClient | None = None,
    items: list[dict] | None = None,
    items_in: Path | None = None,
    save_items: Path | None = None,
    verify_with_llm: bool = True,
) -> CardCheckRun:
    import json as _json

    client = client or default_client()
    if items is None and items_in is not None and Path(items_in).exists():
        items = _json.loads(Path(items_in).read_text(encoding="utf-8"))["items"]
    if items is None:
        items = generate_n(n, source_path=source_path, client=client)
    if save_items is not None:
        Path(save_items).write_text(
            _json.dumps({"n_items": len(items), "items": items}, indent=2),
            encoding="utf-8",
        )
    verify_client = client if (verify_with_llm and ai_enabled()) else None
    _kept, report = block_failing(
        items, gold_path=gold_path, cutoff=cutoff, client=verify_client
    )
    ai_source = "stub"
    for it in items:
        sm = it.get("source_model")
        if sm and sm != "stub":
            ai_source = sm
            break
    return CardCheckRun(
        source=f"generated:{Path(source_path).stem}",
        gold_size=_gold_size(gold_path),
        cutoff=cutoff,
        n_requested=n,
        n_generated=len(items),
        n_passed=report.n_passed,
        n_blocked=report.n_failed,
        correct_useful=report.correct_useful,
        wrong=report.wrong,
        correct_bad_teaching=report.correct_bad_teaching,
        ai_source=ai_source,
        llm_verified=verify_client is not None,
        report=report,
    )


def format_run(r: CardCheckRun) -> str:
    lines = [
        "AI card check (spec 7f)",
        "=" * 40,
        f"Source: {r.source}",
        f"Gold set size: {r.gold_size}",
        f"Pre-set passing cutoff: {r.cutoff}  (stated before results)",
        f"LLM correctness veto: {'on' if r.llm_verified else 'off (offline keyword-only)'}"
        + (f"  [{r.ai_source}]" if r.ai_source != "stub" else ""),
        f"Cards generated: {r.n_generated}/{r.n_requested}",
        "",
        "Three counts:",
        f"  (1) correct & useful:          {r.correct_useful}",
        f"  (2) wrong (worse than no card): {r.wrong}",
        f"  (3) correct-but-bad-teaching:   {r.correct_bad_teaching}",
        "",
        f"PASSED (>= cutoff, kept): {r.n_passed}",
        f"BLOCKED (< cutoff / vetoed): {r.n_blocked}",
    ]
    return "\n".join(lines)


if __name__ == "__main__":  # pragma: no cover
    run = run_card_check()
    print(format_run(run))
