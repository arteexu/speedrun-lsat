def main() -> int:
    data = json.loads(SEED.read_text(encoding="utf-8"))
    existing = {i["id"] for i in data["items"]}
    added = 0
    for item in NEW_ITEMS:
        if item["id"] in existing:
            continue
        # sanity: exactly one correct choice
        n_correct = sum(1 for c in item["choices"] if c.get("correct"))
        assert n_correct == 1, f"{item['id']} must have exactly one correct choice"
        data["items"].append(item)
        existing.add(item["id"])
        added += 1

    # Course grouping (additive, backward-compatible): stamp unit/lesson/order on
    # every item and refresh the deck-level `units` manifest. Deterministic and
    # idempotent, so re-running is safe. Items may carry a hand-authored `unit`
    # already; assign_all preserves those and fills in the rest.
    from speedrun.tools.assign_units import (
        assign_all,
        build_manifest,
        validate_manifest,
    )

    assign_all(data["items"], overwrite=False)
    data["units"] = build_manifest(data["items"])
    validate_manifest(data["items"], data["units"])

    SEED.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Added {added} new items. Total now: {len(data['items'])}.")
    return 0


